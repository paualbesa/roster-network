import QRCode from "qrcode";
import { CopyButton } from "@/components/copy-button";
import { DONATION_ADDRESSES, DONATION_NOTE } from "@/lib/donate";

/** Server component: QR codes are rendered to SVG at build time from the exact address strings. */
export async function DonateGrid({ compact = false }: { compact?: boolean }) {
  const items = await Promise.all(
    DONATION_ADDRESSES.map(async (d) => ({
      ...d,
      qr: await QRCode.toString(d.address, { type: "svg", margin: 1, errorCorrectionLevel: "M", color: { dark: "#07080c", light: "#ffffff" } }),
    })),
  );
  return (
    <div>
      <ul className={`grid gap-4 ${compact ? "sm:grid-cols-2 lg:grid-cols-5" : "sm:grid-cols-2 lg:grid-cols-3"}`}>
        {items.map((d) => (
          <li key={d.id} className="flex flex-col gap-3 border border-line/15 p-4">
            <div className="flex items-baseline justify-between gap-2">
              <p className="font-semibold text-paper">{d.network}</p>
              <p className="font-mono text-[11px] text-muted">{d.symbol}</p>
            </div>
            <div
              className="mx-auto w-full max-w-[160px] overflow-hidden bg-white p-1 [&_svg]:h-auto [&_svg]:w-full"
              role="img"
              aria-label={`QR code for the ${d.network} address`}
              // SVG generated by the qrcode library from a constant address string.
              dangerouslySetInnerHTML={{ __html: d.qr }}
            />
            <div className="flex items-center gap-2">
              <code className="min-w-0 flex-1 break-all font-mono text-[11px] leading-5 text-paper">{d.address}</code>
              <CopyButton value={d.address} label={`${d.network} address`} />
            </div>
          </li>
        ))}
      </ul>
      <p className="mt-4 border-l-2 border-brass px-4 py-3 text-sm text-paper" role="note">
        {DONATION_NOTE}
      </p>
    </div>
  );
}
